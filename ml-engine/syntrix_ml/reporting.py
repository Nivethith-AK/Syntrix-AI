"""Evidence-grounded Markdown + PDF report generation.

Compliant with CS-34 SDGP specification:
- Strictly cites deterministic computed statistics and quality metrics
- Explicitly disclaims causation ("Correlation != Causation")
- Embeds data quality validation status, EDA findings, and optional static chart images
"""

from __future__ import annotations

import io
import re
from datetime import datetime, timezone
from typing import Any

from fpdf import FPDF


def build_markdown_report(
    *,
    title: str = "Data Intelligence Report",
    objective: str | None = None,
    workspace_name: str | None = None,
    semantic_summary: str | None = None,
    quality_report: dict[str, Any] | None = None,
    cleaning_summary: dict[str, Any] | None = None,
    eda: dict[str, Any] | None = None,
    experiment: dict[str, Any] | None = None,
    explanations: dict[str, Any] | None = None,
    recommendations: list[str] | None = None,
) -> str:
    """Build a comprehensive, evidence-grounded Markdown report citing verified figures."""
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# {title}",
        "",
        f"_Generated by Syntrix AI Autonomous Data Intelligence Platform — {now}_",
        "",
    ]

    if objective:
        lines += [
            "## Analytical Objective",
            "",
            f"> **User Objective:** {objective}",
            "",
        ]

    if workspace_name:
        lines += [f"**Workspace:** {workspace_name}", ""]

    # 1. Dataset Overview
    summary = (eda.get("summary") if eda else None) or {}
    lines += [
        "## 1. Dataset Overview",
        "",
    ]
    if semantic_summary:
        lines += [semantic_summary, ""]

    if summary:
        lines += [
            f"- **Total Rows:** {summary.get('row_count', 'N/A')}",
            f"- **Total Columns:** {summary.get('column_count', 'N/A')}",
            f"- **Overall Missing Cells:** {summary.get('missing_cell_pct', 0.0):.2f}%",
            f"- **Duplicate Records Detected:** {summary.get('duplicate_row_count', 0)}",
            "",
        ]

    # 2. Data Quality & Validation Gate
    if quality_report:
        lines += [
            "## 2. Data Quality Validation Gate",
            "",
            f"- **Overall Quality Score:** {quality_report.get('quality_score', 'N/A')}/100",
            f"- **Quality Gate Passed:** {'Passed' if quality_report.get('quality_gate_passed') else 'Flagged with Warnings'}",
            "",
        ]
        issues = quality_report.get("issues") or []
        if issues:
            lines += ["### Identified Quality Issues & Warnings", ""]
            for issue in issues[:8]:
                sev = issue.get("severity", "info").upper()
                col_part = f" (`{issue['column']}`)" if issue.get("column") else ""
                lines.append(f"- **[{sev}]** {issue.get('title')}{col_part}: {issue.get('description')}")
            lines.append("")
        else:
            lines += ["_No severe data quality issues detected._", ""]

    # 3. Data Cleaning & Preparation Summary
    if cleaning_summary:
        actions = (
            cleaning_summary.get("cleaning_actions")
            if isinstance(cleaning_summary, dict)
            else cleaning_summary
        ) or []
        if actions:
            lines += ["## 3. Data Cleaning & Preparation Applied", ""]
            for action in actions:
                desc = action.get("description") or action.get("details") or ""
                lines.append(f"- **{action.get('action')}:** {desc}")
            lines.append("")

    # 4. Exploratory Data Analysis Insights (Evidence Grounded)
    if eda:
        insights = eda.get("insights") or []
        if insights:
            lines += ["## 4. Key Exploratory Findings (Evidence-Grounded)", ""]
            for ins in insights:
                sev_icon = "•"
                title_txt = ins.get("title", "Finding")
                detail_txt = ins.get("detail", "")
                lines.append(f"{sev_icon} **{title_txt}**")
                lines.append(f"  {detail_txt}")
                if ins.get("causality_caveat"):
                    lines.append(f"  _Note: {ins['causality_caveat']}_")
                lines.append("")

        # Correlation details
        correlations = eda.get("correlations") or {}
        pairs = correlations.get("pairs") or []
        if pairs:
            lines += ["### Top Bivariate Associations", ""]
            lines += [
                "| Feature A | Feature B | Pearson r | p-value | Relationship | Significant? |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
            for p in pairs[:5]:
                sig_str = "Yes (p < 0.05)" if p.get("significant") else "No"
                lines.append(
                    f"| `{p['feature_x']}` | `{p['feature_y']}` | {p['pearson_r']} | {p.get('pearson_p_value', 'N/A')} | {p['strength']} | {sig_str} |"
                )
            lines.append("")

        # Categorical associations
        cat_assocs = eda.get("categorical_associations") or []
        if cat_assocs:
            lines += ["### Categorical Dependencies (Chi-Square)", ""]
            for a in cat_assocs[:3]:
                lines.append(
                    f"- **`{a['feature_x']}` vs `{a['feature_y']}`:** Cramer's V = {a['cramers_v']}, chi2 = {a['chi2_statistic']} (p = {a['p_value']})"
                )
            lines.append("")

    # 5. Methodological Constraints & Causality Disclaimer
    lines += [
        "## 5. Statistical Caveats & Causality Boundary",
        "",
        "> **Important Disclaimer:** All numerical findings in this report represent observational descriptive associations. Correlation does not demonstrate or prove causation. Unobserved confounding variables, sampling bias, and domain-specific factors may influence observed metrics. Verified decisions should incorporate domain validation.",
        "",
    ]

    # 6. Actionable Next Steps & Recommendations
    recs = recommendations or _default_recommendations(eda, quality_report)
    if recs:
        lines += ["## 6. Recommendations & Next Steps", ""]
        for r in recs:
            lines.append(f"- {r}")
        lines.append("")

    lines += ["---", "", "_Syntrix AI — Autonomous Data Intelligence Platform._"]
    return "\n".join(lines)


def markdown_to_pdf(
    markdown: str,
    title: str = "Syntrix Data Intelligence Report",
    *,
    chart_images: dict[str, bytes] | None = None,
) -> bytes:
    """Render Markdown report into a professional PDF with optional embedded chart images."""
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_margins(left=15, top=15, right=15)

    # Document Header
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(17, 24, 39)
    _write(pdf, _safe(title), 10)
    pdf.ln(3)

    pdf.set_font("Helvetica", size=9)
    pdf.set_text_color(107, 114, 128)
    _write(pdf, "Syntrix AI Autonomous Data Intelligence Platform - Verified Evidence Report", 5)
    pdf.ln(5)

    # Divider line
    pdf.set_draw_color(229, 231, 235)
    pdf.line(15, pdf.get_y(), 195, pdf.get_y())
    pdf.ln(6)

    pdf.set_text_color(31, 41, 55)

    for raw in markdown.splitlines():
        line = raw.rstrip()
        if not line or line.startswith("|---") or set(line) <= {"-", "|", " "}:
            pdf.ln(2)
            continue

        if line.startswith("# "):
            # Main title already in header, skip or subheader
            continue
        elif line.startswith("## "):
            pdf.ln(4)
            pdf.set_font("Helvetica", "B", 13)
            pdf.set_text_color(17, 24, 39)
            _write(pdf, _strip_md(_safe(line[3:])), 7)
            pdf.set_font("Helvetica", size=10)
            pdf.set_text_color(31, 41, 55)
            pdf.ln(1)
        elif line.startswith("### "):
            pdf.ln(2)
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(55, 65, 81)
            _write(pdf, _strip_md(_safe(line[4:])), 6)
            pdf.set_font("Helvetica", size=10)
            pdf.set_text_color(31, 41, 55)
        elif line.startswith("- "):
            _write(pdf, "  * " + _strip_md(_safe(line[2:])), 5.5)
        elif line.startswith("• "):
            _write(pdf, "  - " + _strip_md(_safe(line[2:])), 5.5)
        elif line.startswith("> "):
            pdf.set_font("Helvetica", "I", 9.5)
            pdf.set_text_color(75, 85, 99)
            _write(pdf, "    " + _strip_md(_safe(line[2:])), 5.5)
            pdf.set_font("Helvetica", size=10)
            pdf.set_text_color(31, 41, 55)
        elif line.startswith("|"):
            pdf.set_font("Courier", size=8.5)
            _write(pdf, _safe(line.replace("|", "  ")), 4.5)
            pdf.set_font("Helvetica", size=10)
        else:
            _write(pdf, _strip_md(_safe(line)), 5.5)

    # Embed Chart Images if provided
    if chart_images:
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 14)
        pdf.set_text_color(17, 24, 39)
        _write(pdf, "Generated Analytical Visualizations", 8)
        pdf.ln(5)

        for chart_name, img_data in chart_images.items():
            if not img_data:
                continue
            try:
                # Add image using memory stream
                img_stream = io.BytesIO(img_data)
                # Check space on current page
                if pdf.get_y() > 200:
                    pdf.add_page()
                pdf.set_font("Helvetica", "B", 10)
                pdf.set_text_color(55, 65, 81)
                _write(pdf, f"Visualization: {chart_name.replace('_', ' ').capitalize()}", 6)
                pdf.ln(2)
                pdf.image(img_stream, w=150)
                pdf.ln(8)
            except Exception:
                continue

    out = pdf.output()
    if isinstance(out, (bytes, bytearray)):
        return bytes(out)
    return str(out).encode("latin-1", errors="ignore")


def _write(pdf: FPDF, text: str, h: float) -> None:
    pdf.set_x(pdf.l_margin)
    try:
        pdf.multi_cell(0, h, text or " ")
    except Exception:
        pdf.set_x(pdf.l_margin)
        pdf.multi_cell(0, h, (text or " ")[:200])


def _strip_md(text: str) -> str:
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"_(.+?)_", r"\1", text)
    text = text.replace("`", "'")
    return text


def _safe(text: str) -> str:
    return (
        text.replace("—", "-")
        .replace("–", "-")
        .replace("·", "-")
        .replace("•", "-")
        .replace("`", "'")
        .replace("“", '"')
        .replace("”", '"')
        .replace("‘", "'")
        .replace("’", "'")
        .encode("latin-1", errors="replace")
        .decode("latin-1")
    )


def _default_recommendations(
    eda: dict[str, Any] | None, quality_report: dict[str, Any] | None
) -> list[str]:
    recs: list[str] = []
    if quality_report and not quality_report.get("quality_gate_passed", True):
        recs.append("Review flagged data quality anomalies before sharing downstream.")
    if eda and (eda.get("summary") or {}).get("missing_cell_pct", 0) > 5:
        recs.append("Investigate missingness mechanism (MCAR vs MAR) to verify imputation assumptions.")
    recs.append("Conduct domain expert validation on top identified bivariate associations.")
    recs.append("Establish automated periodic validation if this dataset is updated incrementally.")
    return recs
